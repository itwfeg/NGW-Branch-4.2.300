#include "bitstring.h"

///////////////////////////////////////////////////////////////////////////////////////////////////
bitstring::bitstring() :
    _Mybase()
{
}

///////////////////////////////////////////////////////////////////////////////////////////////////
bitstring::bitstring( const _Mybase &other ) :
    _Mybase( other )
{
}

///////////////////////////////////////////////////////////////////////////////////////////////////
bitstring::bitstring( const _Myt &other ) :
    _Mybase( other )
{
}

///////////////////////////////////////////////////////////////////////////////////////////////////
bitstring::bitstring( size_t n, value_type val ) :
    _Mybase( n, val )
{
}

///////////////////////////////////////////////////////////////////////////////////////////////////
bitstring::~bitstring()
{
}

///////////////////////////////////////////////////////////////////////////////////////////////////
void bitstring::append( unsigned int value, size_t bits )
{
    if ( !bits )
        return;

    unsigned int mask( 1 );

    while ( --bits )
        mask <<= 1;

    do
    {
        push_back( value & mask ? true : false );
        mask >>= 1;

    } while ( mask );
}

///////////////////////////////////////////////////////////////////////////////////////////////////
void bitstring::append( const std::string &data )
{
    for ( std::string::const_iterator i( data.begin() ); i != data.end(); ++i )
        append( (unsigned char) (*i), 8 );
}

///////////////////////////////////////////////////////////////////////////////////////////////////
void bitstring::append( const _Myt &data )
{
    _Mybase::append( data );
}

