COOLCategory *COOLCategory::findCOOLCategory(HobRecordNum categoryNum, HobRecordNum deptNum, DBAccess *dbAccess)
{
	COOLCategory *readCOOLCategory = (COOLCategory *)NULL;

	if (Debug::isTracing("COOLCategory.find"))
	{
		HobString myDebug("Looking for category number: ");
		myDebug.append(Long::toString(categoryNum));
		Debug::trace("COOLCategory.find", myDebug);
	}

	if (categoryNum <= 0 || !dbAccess)
		return readCOOLCategory;

	edb::DBCoolCategoriesRM	*dbCoolCategoriesRM = dbAccess->getDBCoolCategoriesRM();
	if (!dbCoolCategoriesRM)
		return readCOOLCategory;

	try
	{
		DBCoolCategory *dbCOOLCategoryRec = dbCoolCategoriesRM->findNumber(longtostring(categoryNum), longtostring(deptNum));
		if (dbCOOLCategoryRec)
		{
			Debug::trace("COOLCategory.find", "Found category in database.");

			readCOOLCategory = new COOLCategory(dbCOOLCategoryRec, dbAccess);
			if (!readCOOLCategory)
				delete dbCOOLCategoryRec;
			else
			{
/*
				if (Debug::isTracing("COOLCategory.find"))
				{
					HobString myDebug("COOLCategory object: ");
					myDebug.append(Hex::toString((long) readCOOLCategory);
					myDebug.append("   COOLCategory number: ").append(longtostring(readCOOLCategory->getRecordNum())).append(longtostring(readCOOLCategory->getDeptNum());
					Debug::trace("COOLCategory.find", myDebug);
				}
*/
			}
		}
	}
	catch (DBException &dbe)
	{
		if (Debug::isTracing("DBAccess.exception"))
		{
			Debug::trace("DBAccess.exception", "COOLCategory::findCOOLCategory() ********** database exception **********");
			DBException::Type t = dbe.getType();
			HobString myDebug("   DBException: type: ");
			myDebug.append(Integer::toString(t)).append("  info:").append(dbe.info());
			Debug::trace("DBAccess.exception", myDebug);
		}
	}

	return readCOOLCategory;
}


bool COOLCategory::isRecordValid()
{
	if (myDbRecord)
	 	return myDbRecord->isRecordValid();
	else
		return false;
}

int COOLCategory::deleteRecord()
{
	int result = 0;
	if (myDbRecord && dbAccess)
	{
		DBCoolCategoriesRM	*dbCoolCategoriesRM = dbAccess->getDBCoolCategoriesRM();
		if (dbCoolCategoriesRM)
		{
			if (Debug::isTracing("COOLCategory"))
			{
				HobString myDebug("Deleting COOLCategory: ");
				myDebug.append(name1);
				Debug::trace("COOLCategory", myDebug);
			}
			result = dbCoolCategoriesRM->deleteRecord(myDbRecord);
		}
	}
	return result;
}

void COOLCategory::saveRecord()
{
	if (recordNum > 0 && dbAccess)
	{
		DBCoolCategoriesRM *dbCoolCategoriesRM = dbAccess->getDBCoolCategoriesRM();
		if (!dbCoolCategoriesRM)
			return;

		if (!myDbRecord)
		{
			Debug::trace("COOLCategory", "saveRecord() - don't have a db record, creating it...");
			myDbRecord = dbCoolCategoriesRM->createRecord();
		}

		if (myDbRecord)
		{
			Debug::trace("COOLCategory", "Going to set data elements");

			//	Plug the changes back into the dbCOOLCategory Record
			myDbRecord->setNumber(longtostring(recordNum));
			myDbRecord->setDeptNumber(longtostring(deptNum));
			if (name1.empty())
				myDbRecord->setName1Null();
			else
				myDbRecord->setName1(name1);
			if (name2.empty())
				myDbRecord->setName2Null();
			else
				myDbRecord->setName2(name2);

			try
			{
				dbCoolCategoriesRM->saveRecord(myDbRecord);		//save record to the database
			}
			catch (DBException &dbe)
			{
				Debug::trace("DBAccess.exception", "COOLCategory::saveRecord() ********** database exception **********");
				DBException::Type t = dbe.getType();
				Debug::trace("DBAccess.exception", HobString("     DBException: type:") + HobString(Integer::toString(t)) + HobString("  info:") + dbe.info());
			}
			Debug::trace("COOLCategory", "Saved to the database");
		}
	}
}
