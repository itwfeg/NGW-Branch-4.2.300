#ifndef COMMSESSIONEVENT_H
#define COMMSESSIONEVENT_H



#include "HfcError.h"



class CommSessionEvent
{
	public:
		// Types and subtypes
		typedef enum
		{
			START_EVENT,

			INITIALIZED_EVENT,

			HEADER_RECEIVED_EVENT,

			HEADER_PROCESSED_EVENT,

			HEADER_SENT_EVENT,

			COMMAND_RECEIVED_EVENT,
			READ_ALL_RECEIVED_EVENT,
			DELETE_ALL_RECEIVED_EVENT,
			FOOTER_RECEIVED_EVENT,

			COMMAND_PROCESSED_EVENT,

			READ_ALL_INIT_COMPLETED_EVENT,
			READ_ALL_DONE_EVENT,

			READ_ALL_RECORD_READ_EVENT,

			READ_ALL_RECORD_WRITTEN_EVENT,

			READ_ALL_COMPLETED_EVENT,

			DELETE_ALL_INIT_COMPLETED_EVENT,
			DELETE_ALL_DONE_EVENT,

			DELETE_ALL_RECORD_READ_EVENT,

			DELETE_ALL_RECORD_DELETED_EVENT,

			DELETE_ALL_COMPLETED_EVENT,

			FOOTER_PROCESSED_EVENT,

			FOOTER_SENT_EVENT,

			ERROR_EVENT,
			ERROR_PROCESSED_DISCONNECT_EVENT,
			ERROR_PROCESSED_CONCLUDE_EVENT,

			DISCONNECTED_EVENT,

			HANDLED_ERROR_EVENT,

			END_EVENT
		} eventId_type;

		typedef enum
		{
			COMMERROR_NO_ERROR,

			/* The range between 50 and 99 needs to match the corresponding range in HfcError. */
			COMMERROR_NOT_SYNCHRONIZING_SCALE       = HfcError::ERRORCODE_NOTSYNCHRONIZING,        /* 50 */
			COMMERROR_NOT_A_PRIMARY_SCALE           = HfcError::ERRORCODE_NOTAPRIMARYSCALE,        /* 51 */
			COMMERROR_NOT_A_SECONDARY_SCALE         = HfcError::ERRORCODE_NOTASECONDARYSCALE,      /* 52 */
			COMMERROR_NOT_YOUR_SECONDARY_SCALE      = HfcError::ERRORCODE_NOTYOURSECONDARYSCALE,   /* 53 */
			COMMERROR_SCALE_BUSY                    = HfcError::ERRORCODE_SCALEBUSY,               /* 54 */

			COMMERROR_NOT_PROCESSING_DATA           = 100,
			COMMERROR_CANNOT_CREATE_SOCKET,
			COMMERROR_CANNOT_CONNECT,
			COMMERROR_TIMEDOUT_READING_HEADER,
			COMMERROR_DIDNOT_RECEIVE_HEADER,
			COMMERROR_WRONG_DATA_TYPE,
			COMMERROR_READING_FROM_SOCKET,
			COMMERROR_WRITING_TO_SOCKET,
			COMMERROR_RECEIVED_ERROR,
			COMMERROR_TIMEDOUT_READING_COMMAND,
			COMMERROR_TIMEDOUT_WAITING_FOOTER,

			COMMERROR_LAST
		} CommError;


		// Constructors and destructors
		CommSessionEvent(eventId_type id) : id_(id) {}
		virtual ~CommSessionEvent() {}


		// Accessor methods
		eventId_type getId() const { return id_; }



	private:
		eventId_type id_;
};



#endif // COMMSESSIONEVENT_H
