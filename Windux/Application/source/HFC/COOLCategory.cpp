void COOLCategory::update(const COOLCategory *newCoolCategory)
{
	if (!newCoolCategory)
		return;

	short loopCnt = 1;
	while (loopCnt < endCOOLCategoryFieldOffsets)
	{
		if (newCoolCategory->isReceived(loopCnt))
		{
			switch (loopCnt)
			{
				case fieldOffsetCOOLCategoryDeptNum:
					setDeptNum(newCoolCategory->getDeptNum());
				break;
				case fieldOffsetCOOLCategoryNumber:
					setRecordNum(newCoolCategory->getRecordNum());
					break;
				case fieldOffsetCOOLCategoryName1:
					setName1(newCoolCategory->getName1());
					break;
				case fieldOffsetCOOLCategoryName2:
					setName2(newCoolCategory->getName2());
					break;
				default:
					break;
			}
		}
		loopCnt++;
	}
}


const char *COOLCategory::serialize(int format) const
{
	serializedData = "";

	if (getFormatType() != UnknownFormat)
		format = getFormatType();

	switch (format)
	{
		case BrowserFormat:
			for (int loopCnt = 1; loopCnt < endCOOLCategoryFieldOffsets; loopCnt++)
			{
				if (loopCnt > 1)
					serializedData.append(BrowserFormatSeparator);
				switch (loopCnt)
				{
					case fieldOffsetCOOLCategoryNumber:
						serializedData.append(Long::toString(recordNum));
						break;
					case fieldOffsetCOOLCategoryName1:
					{
						HobString tempName(name1);
						tempName.quoteForCSV();
						serializedData.append(tempName);
						break;
					}
					case fieldOffsetCOOLCategoryName2:
					{
						HobString tempName(name2);
						tempName.quoteForCSV();
						serializedData.append(tempName);
						break;
					}
					default:
						break;
				}
			}
			break;

		case SynchronizationTaggedFormat:
		case EvolutionTaggedFormat:
		case UltimaTaggedFormat:
		case DBIndependentFormatFormat:
		{
			COOLCategoryTags coolTags;
			HobString tag = "";
			HobString fieldData = "";

			std::list<COOLCategoryFieldOffsets>::iterator fieldIter = evolFieldList.begin();
			while (fieldIter != evolFieldList.end())
			{
				tag = coolTags.getTag(*fieldIter);
				switch (*fieldIter)
				{
					case fieldOffsetCOOLCategoryNumber:
						fieldData = Long::toString(recordNum);
						break;
					case fieldOffsetCOOLCategoryName1:
						fieldData =	name1;
						break;
					case fieldOffsetCOOLCategoryName2:
						fieldData =	name2;
						break;
					case fieldOffsetCOOLCategoryDeptNum:
						fieldData = Long::toString(deptNum);
						break;
					default:
						tag = "";
						fieldData = "";
						break;
				}

				if (tag.size())
				{
					serializedData.append(tag);
					serializedData.append(fieldData);
					serializedData.append(UnitSeparator);
				}
				fieldIter++;
			}
			break;
		}

		default:
			serializedData = HobString("COOLCategory::serialize - unknown format:") + HobString(Integer::toString(format));
			// todo - throw exception("invalid format");
			break;
	}
	return serializedData.data();
}


