#include "scanneragent.h"

///////////////////////////////////////////////////////////////////////////////////////////////////
scannerAgent::scannerAgent( QObject *parent ) :
    _Mybase( parent ),
    error_( false )
{
}

///////////////////////////////////////////////////////////////////////////////////////////////////
scannerAgent::~scannerAgent()
{
}

///////////////////////////////////////////////////////////////////////////////////////////////////
QString scannerAgent::errorString() const
{
    return errorMessage_;
}

///////////////////////////////////////////////////////////////////////////////////////////////////
void scannerAgent::setErrorString( const QString &value )
{
    error_ = true;
    errorMessage_ = value;
}

///////////////////////////////////////////////////////////////////////////////////////////////////
void scannerAgent::resetErrorString()
{
    error_ = false;
    errorMessage_.clear();
}
