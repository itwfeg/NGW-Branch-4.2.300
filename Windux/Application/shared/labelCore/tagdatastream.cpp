#include <logmanager.h>

#include "tagdatastream.h"

///////////////////////////////////////////////////////////////////////////////////////////////////
tagDataStream::tagDataStream() :
    _Mybase()
{
    initialize();
}

///////////////////////////////////////////////////////////////////////////////////////////////////
tagDataStream::tagDataStream( QIODevice *d ) :
    _Mybase( d )
{
    initialize();
}

///////////////////////////////////////////////////////////////////////////////////////////////////
tagDataStream::tagDataStream( QByteArray *a, QIODevice::OpenMode mode ) :
    _Mybase( a, mode )
{
    initialize();
}

///////////////////////////////////////////////////////////////////////////////////////////////////
tagDataStream::tagDataStream( const QByteArray& a ) :
    _Mybase( a )
{
    initialize();
}

///////////////////////////////////////////////////////////////////////////////////////////////////
tagDataStream::~tagDataStream()
{
}

///////////////////////////////////////////////////////////////////////////////////////////////////
bool tagDataStream::isDeviceTypeOf( QIODevice *d )
{
    if (( !d ) || ( !d->isReadable() ) || ( 2 > d->bytesAvailable() ))
        return false;

    return ("RT" == d->peek( 2 ));
}

///////////////////////////////////////////////////////////////////////////////////////////////////
void tagDataStream::initialize()
{
    // tag data streams are big endian
    setByteOrder( QDataStream::BigEndian );
}
