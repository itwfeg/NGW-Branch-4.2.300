#include "warning.h"
#include "ui_warning.h"

///////////////////////////////////////////////////////////////////////////////////////////////////
Warning::Warning(QWidget *parent, QString warningText) :
    QWidget(parent),
    ui(new Ui::Warning)
{
    ui->setupUi(this);

    details_ = warningText;

    initialize();


}

///////////////////////////////////////////////////////////////////////////////////////////////////
Warning::~Warning()
{
    delete ui;
}

///////////////////////////////////////////////////////////////////////////////////////////////////
void Warning::initialize()
{
    connect(ui->butDone,    SIGNAL(clicked()),    this,   SLOT(onDoneClicked()));

    ui->lblReasons->setText( details_ );
}

///////////////////////////////////////////////////////////////////////////////////////////////////
void Warning::onDoneClicked()
{
    ui->lblReasons->clear();
    setVisible( false );
}
