COOLCategory::COOLCategory(const char *data, int len, int formatType)
{
#ifdef USE_ACCOUNTANT
	if (dataType == 0)
		dataType = util_acc::registerDataType(dataTypeName);

	util_acc::addInstance(dataType);
#endif

	init();

	switch (formatType)
	{
		case BrowserFormat:
		{
			HobString temp(data, len);
			HobTokenizerCSV tok(&temp, BrowserFormatSeparator);
			HobString token;
			short loopCnt = 1;
			while (tok.next(&token) != -1)
			{
				setReceived(loopCnt, (token.length() == 0) ? false : true);

				switch (loopCnt)
				{
					case fieldOffsetCOOLCategoryNumber:
						setRecordNum(Long::valueOf(token));
						break;
					case fieldOffsetCOOLCategoryName1:
						token.unQuoteForCSV();
						setName1(token);
						break;
					case fieldOffsetCOOLCategoryName2:
						token.unQuoteForCSV();
						setName2(token);
						break;
					default:
						break;
				}
				loopCnt++;
			}

			// Only for the UI, if we didn't receive the deptNum with the Class info, the set the deptNum to the currently active dept.
			// If we don't receive it via comm/merge/restore, or other mechanism in the subsequent cases, then it remains its initial value of 0, the default dept.
			if (!isReceived(fieldOffsetCOOLCategoryDeptNum))
			{
				setDeptNum(Configuration::getInstance()->toIntCfg(fieldOffsetCfgMostRecentActiveDeptNum));
				setReceived(fieldOffsetCOOLCategoryDeptNum, true);
			}
			break;
		}

		case SynchronizationTaggedFormat:
		case EvolutionTaggedFormat:
		case UltimaTaggedFormat:
		case DBIndependentFormatFormat:
		{
			COOLCategoryTags coolTags;

			//convert data to HobString
			HobString evolData(data, len);

			//use the UnitSeparator to parse the string
			HobTokenizerUS tok(&evolData, UnitSeparator);
			HobString temp = "";

			int offset = 0;
			HobTokenTagged *token = dynamic_cast<HobTokenTagged *> (HobToken::create(temp,HobTaggedToken));
			if (token)
			{
				while (tok.next(token) != -1)
				{
					//get the tag and find out what offset goes with the tag
					temp = token->getTag();
					offset = (temp.size()) ? coolTags.getOffset(temp) : 0;
					if (offset)
					{
						setReceived(offset, true);
						temp = token->getData();
						switch (offset)
						{
							case fieldOffsetCOOLCategoryNumber:
								setRecordNum(Long::valueOf(temp));
								break;
							case fieldOffsetCOOLCategoryName1:
								setName1(temp);
								break;
							case fieldOffsetCOOLCategoryName2:
								setName2(temp);
								break;
							case fieldOffsetCOOLCategoryDeptNum:
								setDeptNum((HobRecordNum)Long::valueOf(temp));
								break;
							default:
								break;
						}
					}
				}
				delete token;
			}

			// For comm/backup/restore, if we didn't receive the deptNum with the data and the config parameter is set, set the deptNum to the currently active dept.
			// If we didn't receive the deptNum with the data and the config parameter is NOT set (normal case), deptNum remains its initial value of 0, the default dept.
			if (!isReceived(fieldOffsetCOOLCategoryDeptNum) && Configuration::getInstance()->toBoolCfg(fieldOffsetCfgUseCurrentDeptnumWhenNotReceived))
			{
				setReceived(fieldOffsetCOOLCategoryDeptNum, true);
				setDeptNum(Configuration::getInstance()->toIntCfg(fieldOffsetCfgMostRecentActiveDeptNum));
			}
			break;
		}

		default:
			// todo - throw exception("invalid format");
			break;
	}
}

COOLCategory::COOLCategory(DBCoolCategory *dbCoolCategory, DBAccess *access)
{
#ifdef USE_ACCOUNTANT
	if (dataType == 0)
		dataType = util_acc::registerDataType(dataTypeName);

	util_acc::addInstance(dataType);
#endif

	Debug::trace("COOLCategory", "Constructor passing in a db rec");
	init();

	dbAccess = access;

	if (dbCoolCategory)
	{
		Debug::trace("COOLCategory", "Constructor passing in a db rec - dbrec is not null");
		myDbRecord = dbCoolCategory;

		deptNum   = Long::valueOf(dbCoolCategory->getDeptNumber());
		recordNum = Long::valueOf(dbCoolCategory->getNumber());
		if (!dbCoolCategory->isName1Null())
			name1 = dbCoolCategory->getName1();
		if (!dbCoolCategory->isName2Null())
			name2 = dbCoolCategory->getName2();

		errorCode = RECORD_OK;
	}
//	QUESTION: How do we handle a corrupt COOLCategory record?
}

COOLCategory::~COOLCategory()
{
#ifdef USE_ACCOUNTANT
	util_acc::removeInstance(dataType);
#endif

	if (myDbRecord)
		delete myDbRecord;
}


//	private
void COOLCategory::init()
{
	deptNum     = 0;
	recordNum	= RECORD_NOT_FOUND;
	name1		= "";
	name2		= "";
	errorCode	= RECORD_NOT_FOUND;

	dbAccess	= (DBAccess *)NULL;
	myDbRecord	= (DBCoolCategory *)NULL;

	initFieldList();
}

// static
void COOLCategory::initFieldList()
{
	if (browserList.empty())
	{
		browserList.push_back(fieldOffsetCOOLCategoryNumber);
		browserList.push_back(fieldOffsetCOOLCategoryName1);
		browserList.push_back(fieldOffsetCOOLCategoryName2);
	}
	if (evolFieldList.empty())
	{
		evolFieldList.push_back(fieldOffsetCOOLCategoryDeptNum);
		evolFieldList.push_back(fieldOffsetCOOLCategoryNumber);
		evolFieldList.push_back(fieldOffsetCOOLCategoryName1);
		evolFieldList.push_back(fieldOffsetCOOLCategoryName2);

		COOLCategoryTags coolTags((FieldOffsetsList *)&evolFieldList);
	}

}

