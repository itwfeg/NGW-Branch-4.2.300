#define IOCTL_TYPE_BYTE_READ			0x801
#define IOCTL_TYPE_BYTE_DATA_READ		0x802
#define IOCTL_TYPE_WORD_DATA_READ		0x803
#define IOCTL_TYPE_BLOCK_DATA_READ		0x804
#define IOCTL_TYPE_QUICK_WRITE			0x810
#define IOCTL_TYPE_BYTE_WRITE			0x811
#define IOCTL_TYPE_BYTE_DATA_WRITE		0x812
#define IOCTL_TYPE_WORD_DATA_WRITE		0x813
#define IOCTL_TYPE_BLOCK_DATA_WRITE		0x814

#define IOCTL_SMBUS_QUICK_READ CTL_CODE(	\
			FILE_DEVICE_SMB,				\
			IOCTL_TYPE_QUICK_READ,			\
			METHOD_BUFFERED,				\
			FILE_READ_DATA)

#define IOCTL_SMBUS_BYTE_READ CTL_CODE(	\
			FILE_DEVICE_SMB,			\
			IOCTL_TYPE_BYTE_READ,		\
			METHOD_BUFFERED ,			\
			FILE_READ_DATA)
#define IOCTL_SMBUS_BYTE_DATA_READ CTL_CODE(	\
			FILE_DEVICE_SMB,					\
			IOCTL_TYPE_BYTE_DATA_READ,			\
			METHOD_BUFFERED ,					\
			FILE_READ_DATA)
#define IOCTL_SMBUS_WORD_DATA_READ CTL_CODE(	\
			FILE_DEVICE_SMB,					\
			IOCTL_TYPE_WORD_DATA_READ,			\
			METHOD_BUFFERED ,					\
			FILE_READ_DATA)
#define IOCTL_SMBUS_BLOCK_DATA_READ CTL_CODE(	\
			FILE_DEVICE_SMB,					\
			IOCTL_TYPE_BLOCK_DATA_READ,		\
			METHOD_BUFFERED ,					\
			FILE_READ_DATA)

typedef struct _SMBUS_IOCTL_HEADER {
	UCHAR	deviceAddress;
	UCHAR	command;
	ULONG	length;
	USHORT	type;
} SMBUS_IOCTL_HEADER, *PSMBUS_IOCTL_HEADER;


#define IOCTL_SMBUS_QUICK_WRITE CTL_CODE(	\
			FILE_DEVICE_SMB,				\
			IOCTL_TYPE_QUICK_WRITE,			\
			METHOD_BUFFERED,				\
			FILE_READ_DATA)

#define IOCTL_SMBUS_BYTE_WRITE CTL_CODE(	\
			FILE_DEVICE_SMB,				\
			IOCTL_TYPE_BYTE_WRITE,			\
			METHOD_BUFFERED ,				\
			FILE_WRITE_DATA)
#define IOCTL_SMBUS_BYTE_DATA_WRITE CTL_CODE(	\
			FILE_DEVICE_SMB,					\
			IOCTL_TYPE_BYTE_DATA_WRITE,			\
			METHOD_BUFFERED ,					\
			FILE_WRITE_DATA)
#define IOCTL_SMBUS_WORD_DATA_WRITE CTL_CODE(	\
			FILE_DEVICE_SMB,					\
			IOCTL_TYPE_WORD_DATA_WRITE,		\
			METHOD_BUFFERED ,					\
			FILE_WRITE_DATA)
#define IOCTL_SMBUS_BLOCK_DATA_WRITE CTL_CODE(	\
			FILE_DEVICE_SMB,					\
			IOCTL_TYPE_BLOCK_DATA_WRITE,		\
			METHOD_BUFFERED ,					\
			FILE_WRITE_DATA)

typedef struct _SMBUS_IOCTL_WRITE {
	SMBUS_IOCTL_HEADER header;
	UCHAR	body[2];
} SMBUS_IOCTL_WRITE, *PSMBUS_IOCTL_WRITE;

